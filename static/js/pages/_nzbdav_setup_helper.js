  function buildRclone(p){
    return [
'[nzbdav]',
'type = webdav',
'url = http://nzbdav:3000/',
'vendor = other',
'user = ' + p.wuser,
'pass = ' + (p.wpass ? ('RUN: rclone obscure ' + p.wpass) : 'RUN: rclone obscure <your-webdav-pass>')
    ].join('\n');
  }

  function buildUnionDockerfile(){
    return [
'# Minimal mergerfs image (debian-slim + the Bookworm mergerfs package).',
'FROM debian:bookworm-slim',
'RUN apt-get update \\',
'    && apt-get install -y --no-install-recommends mergerfs fuse3 ca-certificates \\',
'    && rm -rf /var/lib/apt/lists/*',
'ENTRYPOINT ["/usr/bin/mergerfs", "-f"]'
    ].join('\n');
  }

  function buildUnionCompose(p){
    var branches = [p.debridbranch].concat(
      CATS.map(function(c){ return '/source/nzbdav/content/' + c; })
    ).join(':');
    return [
'# debrid-usenet-union: mergerfs aggregate so cli-debrid\'s single file-presence',
'# path sees both debrid (zurg) and usenet (nzbdav) files. Read-only.',
'# Build the image from the Dockerfile above (same folder).',
'services:',
'  debrid-usenet-union:',
'    build:',
'      context: .',
'      dockerfile: Dockerfile',
'    image: debrid-usenet-union/mergerfs:bookworm',
'    container_name: debrid-usenet-union',
'    restart: unless-stopped',
'    cap_add:',
'      - SYS_ADMIN',
'    security_opt:',
'      - apparmor:unconfined',
'    devices:',
'      - /dev/fuse:/dev/fuse',
'    environment:',
'      - TZ=' + p.tz,
'    volumes:',
'      # both providers\' rclone mounts live under this host dir (zurg + nzbdav)',
'      - ' + p.mountbase + ':/source:rslave',
'      - ' + p.uniontarget + ':/target:rshared',
'    command:',
'      - "-o"',
'      - "category.create=ff,cache.files=off,allow_other,use_ino,ro,uid=' + p.puid + ',gid=' + p.pgid + ',minfreespace=0,fsname=debrid-usenet-union"',
'      - "' + branches + '"',
'      - "/target"',
'    healthcheck:',
'      test: ["CMD-SHELL", "mountpoint -q /target && ls /target > /dev/null"]',
'      interval: 60s',
'      timeout: 5s',
'      retries: 3',
'      start_period: 10s'
    ].join('\n');
  }

  function buildConfigBlock(p){
    var mfl = p.useUnion ? p.unioncmount : p.cmount;
    var obj = {
      "Usenet Provider": {
        "enabled": true,
        "provider": "nzbdav",
        "url": p.url,
        "api_token": p.token || "<nzbdav SAB api.key>",
        "download_folder": "__unplayable__",
        "mounted_file_location": p.cmount,
        "retention_days": 5000,
        "enable_nzb_naming": false
      }
    };
    if (p.useUnion) {
      obj["Plex"] = { "mounted_file_location": p.unioncmount };
    }
    return JSON.stringify(obj, null, 2);
  }

  function buildSteps(p){
    var cm = p.useUnion ? p.unioncmount : p.cmount;
    var li = [];
    li.push('Create a folder <code>nzbdav/</code> on your host and save the <code>docker-compose.yml</code> + <code>rclone.conf</code> below into it. In <code>rclone.conf</code>, replace the <code>RUN: rclone obscure …</code> line with the output of <code>rclone obscure ' + esc(p.wpass || '&lt;your-webdav-pass&gt;') + '</code>.');
    li.push('Start it: <code>cd nzbdav &amp;&amp; docker compose up -d</code> — this launches NzbDAV + the rclone mount (the files appear under <code>' + esc(p.mountbase) + '/nzbdav</code> on the host).');
    li.push('In the NzbDAV web UI add your usenet (NNTP) provider + indexers. (Categories are handled automatically in section 2 below.)');
    if (p.useUnion) {
      li.push('<strong>Create the union mount:</strong> make a folder <code>debrid-usenet-union/</code>, save the <code>Dockerfile</code> + <code>docker-compose.yml</code> below into it, then run <code>cd debrid-usenet-union &amp;&amp; docker compose up -d --build</code>. The <code>--build</code> builds a tiny mergerfs image; mergerfs then merges your debrid (zurg) + NzbDAV folders into one read-only mount at <code>' + esc(p.uniontarget) + '</code>. <em>That folder is the union — it\'s created by this compose, you don\'t make it by hand.</em>');
      li.push('Check it populated: <code>ls ' + esc(p.uniontarget) + '</code> should list your merged content.');
      li.push('Bind the union into cli-debrid and point Plex\'s file location at it: add <code>- ' + esc(p.uniontarget) + ':' + esc(cm) + ':rshared</code> to cli-debrid\'s compose, set the config block below (it sets <code>Plex.mounted_file_location = ' + esc(cm) + '</code>), then <code>docker compose up -d --force-recreate cli_debrid</code>.');
    } else {
      li.push('Bind the NzbDAV mount into cli-debrid: add <code>- ' + esc(p.mountbase) + '/nzbdav:' + esc(cm) + ':rshared</code> to cli-debrid\'s compose, apply the config block below, then <code>docker compose up -d --force-recreate cli_debrid</code>.');
    }
    li.push('Add the content folders to your Plex libraries (one per managed category — ' + CATS.map(function(c){ return '<code>' + esc(cm) + '/content/' + esc(c) + '</code>'; }).join(', ') + ') and disable Plex auto-scan on them (cli-debrid triggers scans itself).');
    li.push('<strong>⚠️ Important for library deletes &amp; health checks:</strong> cli-debrid resolves a file\'s on-disk location for deletion/health via <code>Plex.mounted_file_location</code> and <code>File Management.original_files_path</code> — <em>not</em> the NzbDAV mount path. Make sure both point at a path that actually contains your NzbDAV content (the union mount above, or — for an NzbDAV-only box — your NzbDAV mount, e.g. <code>' + esc(cm) + '</code>). If they\'re left at a debrid default like <code>/mnt/zurg/__all__</code> on an NzbDAV-only setup, deletes/health checks look at the wrong (empty) mount and can wrongly flag items as missing.');
    return '<div style="margin-top:8px;"><strong>Deploy steps (run these on your host):</strong><ol class="settings-description" style="line-height:1.6;margin-top:4px;">'
      + li.map(function(s){ return '<li>' + s + '</li>'; }).join('') + '</ol></div>';
  }

