# migrate-files (cli_mount .nzb replay → NzbDAV)
# ---------------------------------------------------------------------------

def do_migrate_files(a):
    base = f"http://{a.nzbdav_host}:{a.port}"
    catmap = dict(DEFAULT_CATEGORY_MAP)
    if a.category_map:
        for pair in a.category_map.split(','):
            if '=' in pair:
                k, v = pair.split('=', 1)
                catmap[k.strip()] = v.strip()

    state_file = os.path.abspath(a.state_file)
    state = {'done': [], 'failed': []}
    if os.path.exists(state_file):
        try:
            state = json.load(open(state_file))
        except Exception:
            pass

    print(f"Replaying cli_mount .nzb files from container '{a.climount_container}' → {base}")
    print("NOTE: best-effort. cli_mount trims old .nzb files; unavailable ones are skipped.\n")

    # Enumerate available .nzb files inside the climount container
    r = subprocess.run(['docker', 'exec', a.climount_container, 'sh', '-c', f'ls {a.climount_nzb_path}'],
                       capture_output=True, text=True)
    if r.returncode != 0:
        print(f"ERROR: cannot list {a.climount_nzb_path} in {a.climount_container}: {r.stderr[:200]}")
        return 1
    nzb_basenames = {f[:-4] for f in r.stdout.split() if f.endswith('.nzb')}
    print(f"Found {len(nzb_basenames)} replayable .nzb files in cli_mount.")

    # Build work list from the mounted climount content folders
    work = []
    for decy_cat, nz_cat in catmap.items():
        folder = os.path.join(a.climount_mount, decy_cat)
        if not os.path.isdir(folder):
            continue
        for release in os.listdir(folder):
            key = f"{decy_cat}/{release}"
            if key in state['done'] or key in state['failed']:
                continue
            if release in nzb_basenames:
                work.append((decy_cat, nz_cat, release))
    print(f"Work list: {len(work)} releases with a replayable .nzb.\n")
    if not work:
        print("Nothing to replay (no matching .nzb files). Consider parallel-fill instead.")
        return 0

    staging = '/tmp/nzbdav_replay_staging'
    os.makedirs(staging, exist_ok=True)
    for i, (decy_cat, nz_cat, release) in enumerate(work, 1):
        key = f"{decy_cat}/{release}"
        # throttle on queue depth
        _wait_queue(base, a.apikey, a.max_queue)
        local = os.path.join(staging, f"{release}.nzb")
        cp = subprocess.run(['docker', 'cp', f"{a.climount_container}:{a.climount_nzb_path}/{release}.nzb", local],
                           capture_output=True, text=True)
        if cp.returncode != 0:
            state['failed'].append(f"{key} (copy-fail)"); _save(state, state_file); continue
        nzo = _submit(base, a.apikey, local, release, nz_cat)
        try:
            os.unlink(local)
        except OSError:
            pass
        if nzo:
            print(f"[{i}/{len(work)}] OK   {key} → {nz_cat} ({nzo[:8]})")
            state['done'].append(key)
        else:
            print(f"[{i}/{len(work)}] FAIL {key} (submit)")
            state['failed'].append(f"{key} (submit-fail)")
        _save(state, state_file)
    print(f"\nDone: {len(state['done'])} replayed, {len(state['failed'])} failed. State: {state_file}")
    return 0


def _wait_queue(base, key, max_slots, poll=2, max_wait=180):
    waited = 0
    while waited < max_wait:
        try:
            q = http_json(f"{base}/api?mode=queue&apikey={key}")['queue']
            if int(q.get('noofslots', 0)) < max_slots:
                return
        except Exception:
            pass
        time.sleep(poll); waited += poll


def _submit(base, key, nzb_path, release, cat):
    # multipart upload via curl (stdlib multipart is clumsy); curl is ubiquitous
    url = (f"{base}/api?mode=addfile&apikey={key}&cat={cat}"
           f"&nzbname={urllib.parse.quote(release)}")
    r = subprocess.run(['curl', '-s', '--max-time', '30', '-X', 'POST', url, '-F', f'name=@{nzb_path}'],
                       capture_output=True, text=True)
    try:
        d = json.loads(r.stdout)
        if d.get('status') and d.get('nzo_ids'):
            return d['nzo_ids'][0]
    except json.JSONDecodeError:
        pass
    return None


def _save(state, path):
    with open(path, 'w') as f:
        json.dump(state, f, indent=2)


