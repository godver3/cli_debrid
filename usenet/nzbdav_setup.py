def do_wizard(a):
    print("== NzbDAV setup assistant ==\n")
    scenario = prompt("Scenario — (f)resh install or (m)igrate from cli_mount?", "f").lower()
    a.nzbdav_host = prompt("NzbDAV host/IP cli-debrid will reach", a.nzbdav_host)
    a.port = prompt("NzbDAV port", a.port)
    a.apikey = prompt("NzbDAV SAB api.key (blank if not created yet)", a.apikey)
    a.mount_base = prompt("Host path mapped to /mnt/remote (parent of the nzbdav mount)", a.mount_base)
    a.container_mount_path = prompt("Path cli-debrid sees the nzbdav mount at", a.container_mount_path)
    a.vfs_cache = prompt("Host path for rclone vfs cache", a.vfs_cache)
    a.vfs_size = prompt("rclone vfs cache max size", a.vfs_size)
    print("  (WebDAV user/password = the credentials you set in NzbDAV → Settings →")
    print("   WebDAV. These are NOT the SAB api.key. If you haven't set them yet, do")
    print("   that in the NzbDAV UI first, then enter them here.)")
    a.webdav_user = prompt("NzbDAV WebDAV user (for rclone)", a.webdav_user)
    a.webdav_pass = prompt("NzbDAV WebDAV password (will be rclone-obscured if possible)", a.webdav_pass)
    a.out = prompt("Output directory for generated files", a.out)
    rc = do_generate(a, interactive=True)
    if scenario.startswith('m'):
        print("\n--- Migration ---")
        print("Generated files set up NzbDAV alongside cli_mount. For the existing")
        print("library, the recommended path is parallel-fill (let new grabs populate")
        print("NzbDAV). If you want to attempt replaying old .nzb files, run:")
        print(f"  python3 {os.path.basename(__file__)} migrate-files --nzbdav-host {a.nzbdav_host} "
              f"--port {a.port} --apikey <api.key> --climount-container climount")
    return rc


def build_parser():
    p = argparse.ArgumentParser(description='NzbDAV setup & migration assistant for cli-debrid')
    sub = p.add_subparsers(dest='cmd')

    def add_common(sp):
        sp.add_argument('--nzbdav-host', default='localhost')
        sp.add_argument('--port', default='3000')
        sp.add_argument('--apikey', default='')

    g = sub.add_parser('generate', help='write compose + rclone.conf + config block')
    add_common(g)
    g.add_argument('--mount-base', default='/srv/DUMB/mnt', help='host path mapped to /mnt/remote')
    g.add_argument('--container-mount-path', default='/mnt/nzbdav', help='where cli-debrid sees the mount')
    g.add_argument('--vfs-cache', default='/mnt/cache/nzbdav-vfs')
    g.add_argument('--vfs-size', default='30G')
    g.add_argument('--webdav-user', default='rclone')
    g.add_argument('--webdav-pass', default='')
    g.add_argument('--puid', default='1000'); g.add_argument('--pgid', default='1000')
    g.add_argument('--tz', default='Etc/UTC')
    g.add_argument('--categories', type=lambda s: [c.strip() for c in s.split(',') if c.strip()], default=None)
    g.add_argument('--out', default='./nzbdav-generated')
    g.add_argument('--cli-debrid-config', default='')
    g.add_argument('--write-config', action='store_true', help='merge the provider block into --cli-debrid-config')

    w = sub.add_parser('wizard', help='interactive walk-through')
    add_common(w)
    w.add_argument('--mount-base', default='/srv/DUMB/mnt')
    w.add_argument('--container-mount-path', default='/mnt/nzbdav')
    w.add_argument('--vfs-cache', default='/mnt/cache/nzbdav-vfs')
    w.add_argument('--vfs-size', default='30G')
    w.add_argument('--webdav-user', default='rclone'); w.add_argument('--webdav-pass', default='')
    w.add_argument('--puid', default='1000'); w.add_argument('--pgid', default='1000'); w.add_argument('--tz', default='Etc/UTC')
    w.add_argument('--categories', default=None)
    w.add_argument('--out', default='./nzbdav-generated')
    w.add_argument('--cli-debrid-config', default=''); w.add_argument('--write-config', action='store_true')

    m = sub.add_parser('migrate-files', help='replay cli_mount .nzb files into NzbDAV (best-effort)')
    add_common(m)
    m.add_argument('--climount-container', default='climount')
    m.add_argument('--climount-nzb-path', default='/app/usenet/nzbs', help='.nzb store inside the container')
    m.add_argument('--climount-mount', default='/srv/DUMB/mnt/debrid/climount', help='host path of climount content folders')
    m.add_argument('--category-map', default='', help='climount_cat=nzbdav_cat,comma-separated')
    m.add_argument('--max-queue', type=int, default=3, help='throttle: keep nzbdav queue below this')
    m.add_argument('--state-file', default='./nzbdav_replay.state.json')

    sub.add_parser('check', help='reminder to run the preflight doctor')
    return p


def main():
    p = build_parser()
    a = p.parse_args()
    if a.cmd == 'generate':
        return do_generate(a)
    if a.cmd == 'wizard':
        return do_wizard(a)
    if a.cmd == 'migrate-files':
        return do_migrate_files(a)
    if a.cmd == 'check':
        print("Run the preflight doctor:\n  python3 nzbdav_migrate.py --config <cli-debrid config.json>")
        return 0
    p.print_help()
    return 1


if __name__ == '__main__':
    sys.exit(main())
