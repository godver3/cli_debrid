#!/usr/bin/env python3
"""
nzbdav setup & migration assistant for cli-debrid.

Generates the Docker/rclone/config files for an NzbDAV usenet backend and walks
you through either a FRESH install or a migration FROM cli_mount — so a new user
can get started, and a cli_mount user can switch, without rediscovering every
gotcha by hand. Generic and stdlib-only: it prompts for your paths/credentials
and writes templated files; it does not hard-code one person's setup.

It is SAFE by default: it writes files into an output directory and prints the
exact next commands. It never starts containers or edits your live config unless
you explicitly pass --write-config / run the migrate-files step.

Subcommands
-----------
  wizard          Interactive walk-through (fresh or migrate). Recommended.
  generate        Non-interactive: write compose + rclone.conf + config block.
  migrate-files   Replay existing cli_mount .nzb files into NzbDAV (file move).
  check           Reminder to run the preflight doctor (nzbdav_migrate.py).

Examples
--------
  python3 nzbdav_setup.py wizard
  python3 nzbdav_setup.py generate --nzbdav-host 192.168.1.50 --apikey KEY \\
      --mount-base /srv/DUMB/mnt --out ./nzbdav-generated
  python3 nzbdav_setup.py migrate-files --nzbdav-host 192.168.1.50 --apikey KEY \\
      --climount-container climount

After generating: review the files, add the categories (printed), `docker compose
up -d` the nzbdav stack, set cli-debrid's Usenet Provider config, restart
cli-debrid, then run nzbdav_migrate.py to verify.
"""

import argparse
import json
import os
import shutil
import subprocess
import sys
import time
import urllib.parse
import urllib.request

# Categories cli-debrid's title heuristic routes video grabs into, plus the
# catch-all fallback. These must exist in NzbDAV (api.categories) or submits are
# rejected. 'music' is recommended (the heuristic can emit it) though cli-debrid
# rarely grabs music.
DEFAULT_CATEGORIES = [
    'movies', 'shows',
    'movies_1080p', 'shows_1080p',
    'movies_2160p', 'shows_2160p',
    'movies_1080p_remux', 'movies_2160p_remux',
    'anime_movies', 'anime_shows',
    '__unplayable__', 'music',
]

# cli_mount-folder -> NzbDAV-category mapping used when replaying files. Edit via
# --category-map k=v,k=v. Defaults map cli_mount's content folders to the cli-debrid
# heuristic category names so replayed files land where cli-debrid/Plex expect them.
DEFAULT_CATEGORY_MAP = {
    'movies': 'movies',
    'movies_1080p': 'movies_1080p',
    'movies_2160p': 'movies_2160p',
    'movies_1080p_remux': 'movies_1080p_remux',
    'movies_2160p_remux': 'movies_2160p_remux',
    'shows': 'shows',
    'shows_1080p': 'shows_1080p',
    'shows_2160p': 'shows_2160p',
    'anime_movies': 'anime_movies',
    'anime_shows': 'anime_shows',
    '__unplayable__': '__unplayable__',
    'music': 'music',
}

COMPOSE_TEMPLATE = """\
# NzbDAV usenet backend for cli-debrid — generated by nzbdav_setup.py
# Two services: nzbdav (SAB-compatible API + WebDAV) and an rclone sidecar that
# mounts NzbDAV's WebDAV so cli-debrid/Plex can read the files.
services:
  nzbdav:
    image: nzbdav/nzbdav:latest
    container_name: nzbdav
    restart: unless-stopped
    ports:
      - "{port}:3000"
    environment:
      - PUID={puid}
      - PGID={pgid}
      - TZ={tz}
      # Lets SAB clients (cli-debrid, Lidarr, …) hit /api?apikey=... without the
      # React frontend redirecting to /login. SAB api.key + WebDAV auth still apply.
      - DISABLE_FRONTEND_AUTH=true
    volumes:
      - ./config:/config
      # Parent-bind (not the mount-target directly) avoids a FUSE-mount conflict;
      # rclone mounts the nzbdav subdir inside this bind.
      - {mount_base}:/mnt/remote:rshared
    healthcheck:
      test: curl -f http://localhost:3000/health || exit 1
      interval: 1m
      retries: 3
      start_period: 30s
      timeout: 5s
    networks:
      - nzbdav_net

  nzbdav_rclone:
    image: rclone/rclone:latest
    container_name: nzbdav_rclone
    restart: unless-stopped
    environment:
      - PUID={puid}
      - PGID={pgid}
      - TZ={tz}
    volumes:
      - {mount_base}:/mnt/remote:rshared
      - ./rclone.conf:/config/rclone/rclone.conf
      - {vfs_cache}:/cache
    cap_add:
      - SYS_ADMIN
    security_opt:
      - apparmor:unconfined
    devices:
      - /dev/fuse:/dev/fuse:rwm
    depends_on:
      nzbdav:
        condition: service_healthy
    command: >
      mount nzbdav: /mnt/remote/nzbdav
        --uid={puid} --gid={pgid}
        --allow-other --links --use-cookies
        --vfs-cache-mode=full
        --vfs-cache-max-size={vfs_size}
        --vfs-cache-max-age=24h
        --buffer-size=0M
        --vfs-read-ahead=128M
        --vfs-read-chunk-size=8M
        --vfs-read-chunk-size-limit=64M
        --dir-cache-time=20s
        --cache-dir=/cache
        --log-level=INFO
    networks:
      - nzbdav_net

networks:
  nzbdav_net:
    driver: bridge
"""

RCLONE_TEMPLATE = """\
[nzbdav]
type = webdav
url = http://nzbdav:3000/
vendor = other
user = {webdav_user}
pass = {webdav_pass}
"""


def prompt(text, default=None):
    suffix = f" [{default}]" if default is not None else ""
    val = input(f"{text}{suffix}: ").strip()
    return val or (default if default is not None else '')


def http_json(url, timeout=15, data=None, method=None):
    req = urllib.request.Request(url, data=data, method=method,
                                 headers={'User-Agent': 'nzbdav-setup/1.0'})
    with urllib.request.urlopen(req, timeout=timeout) as r:
        return json.loads(r.read().decode('utf-8', 'replace'))


def obscure_rclone_pass(plain):
    """Obscure a WebDAV password for rclone.conf if the rclone binary is present.
    Falls back to a clear marker the user must replace."""
    rclone = shutil.which('rclone')
    if rclone and plain:
        try:
            out = subprocess.run([rclone, 'obscure', plain], capture_output=True, text=True, timeout=10)
            if out.returncode == 0 and out.stdout.strip():
                return out.stdout.strip()
        except Exception:
            pass
    return plain  # caller is warned to run: rclone obscure <pass>


