# generate
# ---------------------------------------------------------------------------

def do_generate(a, interactive=False):
    out = os.path.abspath(a.out)
    nzbdav_dir = os.path.join(out, 'nzbdav')
    os.makedirs(os.path.join(nzbdav_dir, 'config'), exist_ok=True)

    pass_obscured = obscure_rclone_pass(a.webdav_pass) if a.webdav_pass else 'RUN: rclone obscure <your-webdav-pass>'
    rclone_pass_warn = (pass_obscured == a.webdav_pass and bool(a.webdav_pass)) or pass_obscured.startswith('RUN:')

    compose = COMPOSE_TEMPLATE.format(
        port=a.port, puid=a.puid, pgid=a.pgid, tz=a.tz,
        mount_base=a.mount_base, vfs_cache=a.vfs_cache, vfs_size=a.vfs_size,
    )
    rclone = RCLONE_TEMPLATE.format(webdav_user=a.webdav_user, webdav_pass=pass_obscured)

    with open(os.path.join(nzbdav_dir, 'docker-compose.yml'), 'w') as f:
        f.write(compose)
    with open(os.path.join(nzbdav_dir, 'rclone.conf'), 'w') as f:
        f.write(rclone)

    # cli-debrid Usenet Provider config block to merge into config.json
    provider_cfg = {
        "Usenet Provider": {
            "enabled": True,
            "provider": "nzbdav",
            "url": f"http://{a.nzbdav_host}:{a.port}",
            "api_token": a.apikey or "<nzbdav api.key>",
            "download_folder": "__unplayable__",
            "mounted_file_location": a.container_mount_path,
            "retention_days": 1500,
            "enable_nzb_naming": False,
        }
    }
    cfg_path = os.path.join(out, 'cli_debrid.usenet_provider.json')
    with open(cfg_path, 'w') as f:
        json.dump(provider_cfg, f, indent=2)

    cats = a.categories or list(DEFAULT_CATEGORIES)
    notes = _setup_notes(a, cats, rclone_pass_warn)
    with open(os.path.join(out, 'SETUP_NOTES.md'), 'w') as f:
        f.write(notes)

    print(f"\nGenerated into: {out}")
    print(f"  nzbdav/docker-compose.yml")
    print(f"  nzbdav/rclone.conf            (WebDAV remote)")
    print(f"  cli_debrid.usenet_provider.json")
    print(f"  SETUP_NOTES.md                (READ THIS — step-by-step)")
    if rclone_pass_warn:
        print("\n  NOTE: rclone password is NOT obscured (rclone binary not found or no pass given).")
        print("        Run `rclone obscure <pass>` and paste the result into nzbdav/rclone.conf.")
    if a.write_config and a.cli_debrid_config:
        _merge_into_config(a.cli_debrid_config, provider_cfg)
    print("\nNext: open SETUP_NOTES.md and follow the steps.")
    return 0


def _setup_notes(a, cats, rclone_pass_warn):
    out_dir = os.path.abspath(a.out)
    catlist = ', '.join(c for c in cats if c != 'music')  # music shown as optional
    return f"""# NzbDAV setup — next steps

Generated for nzbdav at http://{a.nzbdav_host}:{a.port}

## 1. Start the NzbDAV stack
```
cd {os.path.abspath(a.out)}/nzbdav
docker compose up -d
```
Open http://{a.nzbdav_host}:{a.port}, finish first-run setup, and add your usenet
(NNTP) provider + indexers in the NzbDAV UI. Copy the SAB **api.key** (Settings →
API) — cli-debrid needs it.

{"**rclone password**: the generated rclone.conf password is a placeholder/plain — run `rclone obscure <your-webdav-pass>` and paste the result as `pass =`." if rclone_pass_warn else ""}

## 2. Add the categories cli-debrid uses
A "category" is just the sub-folder NzbDAV files land in. cli-debrid auto-sorts
grabs into these — they MUST exist in NzbDAV or submits are rejected (items loop
in "Wanted"):
  Required: {catlist}
  Optional: music  (only if you also grab music; harmless to add)

Easiest — in the NzbDAV web UI: **Settings → Categories**, add each name above.

Or from the command line (for this generated stack the NzbDAV database is at
`{out_dir}/nzbdav/config/db.sqlite`):
```
python3 nzbdav_migrate.py --nzbdav-db {out_dir}/nzbdav/config/db.sqlite --fix
```
That adds only the missing categories (don't hand-write a raw SQL `||` append —
re-running it creates duplicates).

## 3. Bind the nzbdav mount into cli-debrid
Add to cli-debrid's docker-compose volumes (so it can resolve files). Use
`:rshared` — with `:rslave` the mount drops as "Transport endpoint not connected"
after an rclone-sidecar restart:
```
- {a.mount_base}/nzbdav:{a.container_mount_path}:rshared
```
Until PR #425 is merged, also add the overlay binds from this patch (see README).

## 4. Set cli-debrid's Usenet Provider config
Merge cli_debrid.usenet_provider.json into cli-debrid's config.json (Settings →
Required → Usenet Provider), set the api_token to the NzbDAV api.key, then restart
cli-debrid.

## 5. Add the category paths to Plex
| Plex library | Add these folders |
|---|---|
| Movies | {a.container_mount_path}/content/movies , {a.container_mount_path}/content/movies_1080p_264 |
| Shows  | {a.container_mount_path}/content/shows  , {a.container_mount_path}/content/shows_1080p_264 |
Disable Plex auto-scan on these FUSE paths (inotify doesn't propagate); cli-debrid
triggers scans itself.

## 6. Verify
```
python3 nzbdav_migrate.py --config <cli-debrid config.json>
```
Should report no blocking issues.

## (Migration only) Move existing cli_mount files
NzbDAV has no copy of your old grabs. Options:
- **Recommended:** run NzbDAV in parallel and let NEW grabs fill it; let the old
  cli_mount library age out. Robust, no surprises.
- **Replay** old .nzb files (best-effort — cli_mount trims old .nzb files, so a
  large fraction may be unavailable, and some replays double-nest folders):
  ```
  python3 nzbdav_setup.py migrate-files --nzbdav-host {a.nzbdav_host} --port {a.port} \\
      --apikey <api.key> --climount-container climount
  ```
Do NOT hard-swap mounts under Plex — a video section can purge "missing" items.
"""


def _merge_into_config(path, block):
    try:
        with open(path) as f:
            cfg = json.load(f)
        cfg.setdefault('Usenet Provider', {}).update(block['Usenet Provider'])
        bak = path + '.bak.nzbdav_setup'
        if not os.path.exists(bak):
            shutil.copy2(path, bak)
        with open(path, 'w') as f:
            json.dump(cfg, f, indent=2)
        print(f"  merged Usenet Provider block into {path} (backup: {bak})")
    except Exception as e:
        print(f"  WARN: could not merge into {path}: {e}")


